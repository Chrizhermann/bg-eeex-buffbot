def _assert_only_general_luajit_assignments(ini: str, version: str) -> None:
    expected = {
        "LuaPatchMode": "REPLACE_INTERNAL_WITH_EXTERNAL",
        "LuaLibrary": "lua51.dll",
        "LuaVersionExternal": version,
    }
    found: dict[str, list[tuple[str | None, str]]] = {
        key: [] for key in expected
    }
    section: str | None = None
    for line in ini.splitlines():
        header = re.fullmatch(r"\[([^]]+)]", line)
        if header:
            section = header.group(1)
            continue
        assignment = re.fullmatch(
            r"(LuaPatchMode|LuaLibrary|LuaVersionExternal)=(.*)", line
        )
        if assignment:
            found[assignment.group(1)].append((section, assignment.group(2)))

    for key, value in expected.items():
        assert found[key] == [("General", value)]
    assert ini.index("LuaPatchMode=") < ini.index("[Auto-Generated]")
    assert "SyntheticAutoGeneratedValue=preserve-me" in ini
    assert "SyntheticPattern=preserve-me-too" in ini


