def _official_loader_ini(
    general_assignments: tuple[str, ...] = (),
    hardcoded_assignments: tuple[str, ...] = (),
    *,
    newline: str = "\n",
) -> str:
    """Return an InfinityLoader.ini shaped like the files shipped by EEex."""
    return newline.join(
        (
            "[General]",
            "Debug=0",
            *general_assignments,
            "Pause=0",
            "",
            "[Auto-Generated]",
            "SyntheticAutoGeneratedValue=preserve-me",
            "",
            "[Hardcoded_InternalLuaState]",
            "SyntheticPattern=preserve-me-too",
            *hardcoded_assignments,
            "",
        )
    )


